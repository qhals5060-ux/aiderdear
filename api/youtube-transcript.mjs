const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;

function jsonArrayAt(text, start) {
  let depth = 0;
  let quoted = false;
  let escaped = false;
  for (let index = start; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') quoted = false;
      continue;
    }
    if (character === '"') quoted = true;
    else if (character === '[') depth += 1;
    else if (character === ']' && --depth === 0) return text.slice(start, index + 1);
  }
  return '';
}

function transcriptText(payload) {
  return (Array.isArray(payload?.events) ? payload.events : [])
    .flatMap(event => Array.isArray(event?.segs) ? event.segs : [])
    .map(segment => segment?.utf8 || '')
    .join(' ');
}

function sentenceList(text) {
  const cleaned = String(text || '')
    .replace(/\[(music|applause|laughter)\]/ig, '')
    .replace(/\s+/g, ' ')
    .trim();
  const chunks = cleaned.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [];
  const sentences = [];
  for (const chunk of chunks) {
    const value = chunk.replace(/^[-–—\s]+/, '').trim();
    if (!value || !/[A-Za-z]/.test(value)) continue;
    if (value.length <= 150) sentences.push(value);
    else {
      const words = value.split(' ');
      let line = '';
      for (const word of words) {
        if (`${line} ${word}`.trim().length > 120 && line) {
          sentences.push(line.trim());
          line = word;
        } else line = `${line} ${word}`.trim();
      }
      if (line) sentences.push(line);
    }
  }
  return [...new Set(sentences)].slice(0, 80);
}

export async function extractTranscript(videoId) {
  if (!VIDEO_ID.test(String(videoId || ''))) throw new Error('올바른 YouTube 영상 ID가 아닙니다.');
  const headers = {
    'accept-language': 'en-US,en;q=0.9',
    'user-agent': 'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/124 Mobile Safari/537.36'
  };
  const watchResponse = await fetch(`https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}&hl=en`, {headers});
  if (!watchResponse.ok) throw new Error('YouTube 영상 정보를 불러오지 못했습니다.');
  const html = await watchResponse.text();
  const marker = '"captionTracks":';
  const markerIndex = html.indexOf(marker);
  if (markerIndex < 0) throw new Error('공개 자막이 없는 영상입니다.');
  const arrayStart = html.indexOf('[', markerIndex + marker.length);
  const rawTracks = jsonArrayAt(html, arrayStart);
  if (!rawTracks) throw new Error('자막 목록을 해석하지 못했습니다.');
  const tracks = JSON.parse(rawTracks);
  const track = tracks.find(item => /^en(?:-|$)/i.test(item?.languageCode || '') && item?.kind !== 'asr')
    || tracks.find(item => /^en(?:-|$)/i.test(item?.languageCode || ''))
    || tracks.find(item => item?.kind !== 'asr')
    || tracks[0];
  if (!track?.baseUrl) throw new Error('사용 가능한 자막 트랙이 없습니다.');
  const captionUrl = new URL(track.baseUrl, 'https://www.youtube.com');
  captionUrl.searchParams.set('fmt', 'json3');
  const captionResponse = await fetch(captionUrl, {headers});
  if (!captionResponse.ok) throw new Error('자막 데이터를 불러오지 못했습니다.');
  const captionText = await captionResponse.text();
  if (!captionText.trim()) throw new Error('YouTube가 자막 데이터 접근을 허용하지 않았습니다.');
  const sentences = sentenceList(transcriptText(JSON.parse(captionText)));
  if (!sentences.length) throw new Error('학습할 문장을 찾지 못했습니다.');
  return {
    sentences,
    language: track.languageCode || '',
    autoGenerated: track.kind === 'asr'
  };
}

export default async function handler(request, response) {
  if (request.method !== 'GET') {
    response.setHeader('Allow', 'GET');
    return response.status(405).json({ok:false, error:'GET 요청만 지원합니다.'});
  }
  try {
    const videoId = String(request.query?.videoId || '');
    const result = await extractTranscript(videoId);
    response.setHeader('Cache-Control', 'public, max-age=0, s-maxage=3600, stale-while-revalidate=86400');
    return response.status(200).json({ok:true, ...result});
  } catch (error) {
    return response.status(422).json({ok:false, error:String(error?.message || error)});
  }
}
